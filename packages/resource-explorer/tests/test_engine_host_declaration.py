"""Test 9 of the engine-host design (§5.2): the generated Dr.Egeria declaration equals the registry.

The document under docs/dr-egeria/engine-host/ is generated by scripts/generate_engine_host_declaration.py from
DATABASE_STEP_REGISTRY. Its request type, guards and step key must match the registry entry and the names the
sweep dispatches on (engine_host.py), so changing either side fails here. It is never run automatically: the
owner runs it, so it must not be a bootstrap batch.
"""
from __future__ import annotations

import importlib.util
import re
import subprocess
import sys
from pathlib import Path

PKG = Path(__file__).resolve().parent.parent
SCRIPT = PKG / "scripts" / "generate_engine_host_declaration.py"
DOC = PKG / "docs" / "dr-egeria" / "engine-host" / "resource-explorer-survey-engine.md"


def _script():
    spec = importlib.util.spec_from_file_location("generate_engine_host_declaration", SCRIPT)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _section(doc: str, command: str, heading: str, nth: int = 0) -> str:
    """The value under `### heading` in the nth `## command` block."""
    blocks = [b for b in doc.split("\n## ") if b.startswith(command + "\n")]
    block = blocks[nth]
    m = re.search(r"^### " + re.escape(heading) + r"\n(.*?)(?=\n### |\n___|\Z)", block, re.S | re.M)
    assert m, f"no '### {heading}' under '## {command}'"
    return m.group(1).strip()


def test_the_committed_document_is_what_the_generator_writes():
    assert DOC.read_text() == _script().render(), \
        "the engine-host declaration is stale: run scripts/generate_engine_host_declaration.py"


def test_check_mode_passes_on_the_committed_tree():
    out = subprocess.run([sys.executable, str(SCRIPT), "--check"], capture_output=True, text=True, timeout=120)
    assert out.returncode == 0, out.stdout + out.stderr


def test_request_type_guards_and_step_key_match_the_registry_entry():
    from resource_explorer import engine_host
    from resource_explorer.surveyors.database.survey_definition_adapter import DATABASE_STEP_REGISTRY

    info = DATABASE_STEP_REGISTRY["db_derived"]
    doc = DOC.read_text()

    gat_qn = _section(doc, "Create Governance Action Type", "Qualified Name")
    assert gat_qn == "ResourceExplorerSurvey::re-db-derived"
    assert _section(doc, "Create Governance Action Type", "Description") == info.description
    guards = [g.strip() for g in _section(doc, "Create Governance Action Type", "Produced Guards").split(",")]
    assert guards == ["survey-completed", "survey-invalid", "survey-failed"]
    assert tuple(guards) == engine_host.SURVEY_GUARDS
    props = _section(doc, "Create Governance Action Type", "Additional Properties")
    assert f"| re_analysis_step | {info.step_key} |" in props
    assert "| executes_at | resource-explorer |" in props

    assert _section(doc, "Link Action to Action Executor", "Governance Action Type") == gat_qn
    assert _section(doc, "Link Action to Action Executor", "Governance Engine") == "ResourceExplorerSurvey"
    assert _section(doc, "Link Action to Action Executor", "Request Type") == "re-db-derived"

    # The sweep dispatches on exactly what the document declares.
    assert engine_host.supported_request_types() == {"re-db-derived": "db_derived"}
    assert engine_host.ENGINE_QUALIFIED_NAME == "ResourceExplorerSurvey"


def test_changing_the_registry_entry_changes_the_document(monkeypatch):
    from resource_explorer.surveyors.database import survey_definition_adapter as adapter

    original = adapter.DATABASE_STEP_REGISTRY["db_derived"]
    from dataclasses import replace

    monkeypatch.setitem(adapter.DATABASE_STEP_REGISTRY, "db_derived",
                        replace(original, description="Something else entirely."))
    assert _script().render() != DOC.read_text()


def test_the_declaration_is_never_a_bootstrap_batch():
    """The owner runs this document. A `_batch.json` beside it would make RE's bootstrap monitor
    write it to Egeria on its own every ten minutes."""
    from resource_explorer import bootstrap

    assert not (DOC.parent / "_batch.json").exists()
    assert "engine-host" not in [b.batch_id for b in bootstrap.discover_batches()]


STEPS = DOC.with_name(DOC.stem + ".pyegeria-steps.json")


def test_the_committed_pyegeria_steps_are_what_the_generator_writes():
    assert STEPS.read_text() == _script().render_steps(), \
        "the engine-host pyegeria steps are stale: run scripts/generate_engine_host_declaration.py"


def test_the_pyegeria_steps_declare_engine_then_service_then_link_with_the_registry_names():
    import json

    from resource_explorer import engine_host

    steps = json.loads(STEPS.read_text())["steps"]
    assert [s["command"] for s in steps] == [
        "Create Survey Action Engine", "Create Survey Action Service", "Link Supported Governance Service"]
    engine, service, link = steps
    assert engine["qualified_name"] == engine_host.ENGINE_QUALIFIED_NAME == "ResourceExplorerSurvey"
    assert engine["display_name"] == engine_host.ENGINE_DISPLAY_NAME
    assert "outside any Egeria engine host" in engine["description"]
    assert service["qualified_name"] == engine_host.service_qualified_name("db_derived") \
        == "SurveyActionService::ResourceExplorerSurvey::db_derived"
    assert (link["governance_engine"], link["governance_service"]) == (engine["qualified_name"],
                                                                         service["qualified_name"])
    assert link["request_type"] == link["service_request_type"] == "re-db-derived"


def test_the_runner_plans_the_committed_declaration_in_the_order_that_works(monkeypatch):
    """Engine, service, SupportedGovernanceService link, THEN the action type and its executor link (which
    resolves the engine by name). A dry run: no client, no subprocess, no row."""
    from resource_explorer import dr_egeria_runner

    monkeypatch.delenv("RE_DR_EGERIA_DOCS_DIR", raising=False)
    out = dr_egeria_runner.run_document("engine-host/resource-explorer-survey-engine.md", dry_run=True)
    assert out["valid"] is True, out["errors"]
    assert [(c["kind"], c["command"]) for c in out["commands"]] == [
        ("pyegeria", "Create Survey Action Engine"), ("pyegeria", "Create Survey Action Service"),
        ("pyegeria", "Link Supported Governance Service"),
        ("dr_egeria", "Create Governance Action Type"), ("dr_egeria", "Link Action to Action Executor")]
    assert out["not_safe_to_repeat"] == ["Link Action to Action Executor"]


