-- Every measure line below is copied verbatim from that file. Only the measures slice 1 of the value
-- profile needs are kept, and the CTE/FROM scaffolding is dropped: Resource Explorer assembles ONE
-- aggregate SELECT per table from these per-column measures (surveyors/database/quality/value_profile.py)
-- instead of one query per column. The TG-IF block names are upstream's flags, evaluated by general_type:
--   is_table              once per table (upstream: in every branch)
--   is_type_A             general_type = 'A'  (whole-table and, with no sampling, the sampleable measures)
--   is_not_A              general_type <> 'A'
--   is_distinct_countable general_type NOT IN ('A', 'X')  (upstream also counts the X types it can compare;
--                         slice 1 does not profile X distinct counts)
--   is_type_D             general_type = 'D'
-- Placeholders: {COL_NAME}, {DATA_SCHEMA}, {DATA_TABLE} (identifiers, double quotes doubled) and
-- {RUN_DATE} ('YYYY-MM-DD HH:MM:SS', generated by Resource Explorer, never user input).
-- A `<%NAME;...%>` call is upstream's templated function (templated_functions.yaml beside this file), expanded
-- in the vendored text before any placeholder is filled.
-- TG-IF is_table
    COUNT(*) AS record_ct,
-- TG-ENDIF
-- TG-IF is_type_A
    COUNT("{COL_NAME}") AS value_ct,
    COUNT(DISTINCT "{COL_NAME}") AS distinct_value_ct,
    SUM(CASE WHEN "{COL_NAME}" IS NULL THEN 1 ELSE 0 END) AS null_value_ct,
    SUM(CASE
          WHEN "{COL_NAME}" = '' THEN 1
                               ELSE 0
        END) AS zero_length_ct,
    SUM( CASE
           WHEN LOWER("{COL_NAME}") SIMILAR TO '(.{1,}|-{1,}|\?{1,}|\s{1,}|0{2,}|9{2,}|x{2,}|z{2,})' THEN 1
           WHEN LOWER("{COL_NAME}") IN ('blank','error','missing','tbd',
                                      'n/a','#na','none','null','unknown')           THEN 1
           WHEN LOWER("{COL_NAME}") IN ('(blank)','(error)','(missing)','(tbd)',
                                      '(n/a)','(#na)','(none)','(null)','(unknown)') THEN 1
           WHEN LOWER("{COL_NAME}") IN ('[blank]','[error]','[missing]','[tbd]',
                                      '[n/a]','[#na]','[none]','[null]','[unknown]') THEN 1
                                                                                     ELSE 0
         END ) AS filled_value_ct,
-- TG-ENDIF
-- TG-IF is_not_A
  COUNT("{COL_NAME}") AS value_ct,
  SUM(CASE WHEN "{COL_NAME}" IS NULL THEN 1 ELSE 0 END) AS null_value_ct,
-- TG-ENDIF
-- TG-IF is_distinct_countable
  COUNT(DISTINCT "{COL_NAME}") AS distinct_value_ct,
-- TG-ENDIF
-- TG-IF is_type_D
  CASE
         WHEN MIN("{COL_NAME}") IS NULL THEN NULL
         ELSE GREATEST(MIN("{COL_NAME}"), '0001-01-01')
       END AS min_date,
  MAX("{COL_NAME}") AS max_date,
  SUM(CASE
          WHEN <%DATEDIFF_MONTH;"{COL_NAME}";'{RUN_DATE}'%> > 240 THEN 1
                                                              ELSE 0
        END) AS before_20yr_date_ct,
  SUM(CASE
        WHEN "{COL_NAME}" > '{RUN_DATE}' THEN 1 ELSE 0
      END) AS future_date_ct,
-- TG-ENDIF
